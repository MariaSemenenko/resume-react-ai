const getSavedLanguage = () => {
  try {
    return localStorage.getItem('site-language')
  } catch {
    return null
  }
}

const savedLanguage = getSavedLanguage()
const initialLanguage = savedLanguage === 'uk' ? 'uk' : 'en'

i18n.use(initReactI18next).init({
  resources: { en: { translation: {} }, uk: { translation: uk } },
  lng: initialLanguage,
  fallbackLng: 'en',
  keySeparator: false,
  interpolation: { escapeValue: false },
})

document.documentElement.lang = initialLanguage
i18n.on('languageChanged', (language) => {
  const safeLanguage = language === 'uk' ? 'uk' : 'en'
  document.documentElement.lang = safeLanguage
  try {
    localStorage.setItem('site-language', safeLanguage)
  } catch {
    // The language still changes for this session when storage is unavailable.
  }
})

export default i18n
